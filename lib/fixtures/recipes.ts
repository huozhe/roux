import type { Playlist, Recipe } from "@/lib/types";
import { parseTimestamp } from "@/lib/format";

type RawIng = { qty: string; name: string };
type RawStep = { t: string; text: string };

function ingredients(list: RawIng[]): Recipe["ingredients"] {
  return list.map(({ qty, name }) => {
    const inferred = qty.startsWith("[") && qty.endsWith("]");
    return {
      qty: inferred ? qty.slice(1, -1) : qty,
      name,
      inferred,
    };
  });
}

function steps(list: RawStep[]): Recipe["steps"] {
  return list.map((s, i) => ({
    n: i + 1,
    text: s.text,
    t_seconds: parseTimestamp(s.t),
  }));
}

